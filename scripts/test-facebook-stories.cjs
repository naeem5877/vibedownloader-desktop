/*
 * Facebook Stories.
 *
 * Two groups. The offline ones run always, because a Facebook outage is not a
 * reason to be unable to check that URL parsing and cookie handling still work.
 * The live ones need the app's saved Facebook session and are skipped without
 * it, following the pattern in test-instagram-stories-local.cjs.
 *
 * The live fetch is the only thing that can catch the failure this module
 * exists to prevent. Facebook answers an HTTP 400 to a request missing
 * `Sec-Fetch-Site`, which is indistinguishable from "your cookies are wrong"
 * unless something actually asks for a story and looks at what came back. That
 * check is why these tests talk to the compiled module instead of asserting on
 * source text.
 *
 *   npm run build:electron && node scripts/test-facebook-stories.cjs
 */

const test = require('node:test');
const assert = require('node:assert');
const fs = require('fs');
const path = require('path');

const REPO = path.resolve(__dirname, '..');
const DST = path.join(REPO, 'dist-electron');
const SRC = path.join(REPO, 'electron');

const {
    isFacebookStoryUrl,
    parseFacebookStoryUrl,
    canonicalStoryUrl,
    decodeStoryToken,
    cookieHeaderFromNetscape,
    fetchFacebookStory,
    buildFacebookStoryMetadata,
    FacebookStoryError
} = require(path.join(DST, 'utils', 'facebookStories.js'));

/** Mirrors a real browser export, including the HttpOnly marker on auth cookies. */
const NETSCAPE = [
    '# Netscape HTTP Cookie File',
    '# This file is generated by a browser extension. Do not edit.',
    '#HttpOnly_.facebook.com\tTRUE\t/\tTRUE\t0\tc_user\t1234567890',
    '#HttpOnly_.facebook.com\tTRUE\t/\tTRUE\t0\txs\tsecret-session-value',
    '.facebook.com\tTRUE\t/\tTRUE\t0\tfr\tabc123',
    '',
    'malformed line without enough columns'
].join('\n');

test('story URLs are recognised, and other Facebook URLs are not', () => {
    for (const url of [
        'https://www.facebook.com/stories/172307927585571/UzpfSVNDOjExMTc3MjU4NDc0OTAxNDQ=/?bucket_count=9',
        'https://www.facebook.com/stories/172307927585571/',
        'https://www.facebook.com/permalink.php?story_fbid=1117725847490144&id=172307927585571',
        'https://www.facebook.com/permalink.php?id=172307927585571&story_fbid=1117725847490144',
        'https://www.facebook.com/story.php?story_fbid=1117725847490144',
        'https://www.facebook.com/story_tray/?bucket_id=172307927585571&story_fbid=1117725847490144',
        'https://m.facebook.com/stories/172307927585571/UzpfSVNDOjEzOTU3NA=='
    ]) {
        assert.ok(isFacebookStoryUrl(url), `should be a story: ${url}`);
    }

    // These all reach yt-dlp instead, which handles them.
    for (const url of [
        'https://www.facebook.com/watch/?v=1234567890',
        'https://www.facebook.com/reel/1234567890',
        'https://www.facebook.com/somepage/videos/101500000/',
        'https://www.facebook.com/',
        'https://www.facebook.com/story_tray/?bucket_id=172307927585571',
        'https://www.instagram.com/stories/example/123/'
    ]) {
        assert.ok(!isFacebookStoryUrl(url), `should not be a story: ${url}`);
    }
});

test('the tray form is rewritten to the permalink that carries the media', () => {
    // The tray page is a client-side shell, so it is the one form that has to be
    // turned into a request for a different URL.
    const tray = 'https://www.facebook.com/story_tray/?bucket_id=172307927585571&story_fbid=1117725847490144';
    const ref = parseFacebookStoryUrl(tray);
    assert.equal(ref.storyFbId, '1117725847490144');
    assert.equal(ref.pageId, '172307927585571');
    assert.equal(canonicalStoryUrl(ref), 'https://www.facebook.com/permalink.php?story_fbid=1117725847490144&id=172307927585571');

    // Nothing to rewrite to when the link does not name a story.
    assert.equal(canonicalStoryUrl({ pageId: '172307927585571' }), null);
});

test('the story id is read out of the token, which is where it is hiding', () => {
    // The URL's base64 is `S:_ISC:1117725847490144`. Nothing else in the link
    // says which story this is, so losing it means losing the filename.
    assert.equal(decodeStoryToken('UzpfSVNDOjExMTc3MjU4NDc0OTAxNDQ='), '1117725847490144');

    const ref = parseFacebookStoryUrl('https://www.facebook.com/stories/172307927585571/UzpfSVNDOjExMTc3MjU4NDc0OTAxNDQ=/?bucket_count=9');
    assert.equal(ref.pageId, '172307927585571');
    assert.equal(ref.storyFbId, '1117725847490144');

    const permalink = parseFacebookStoryUrl('https://www.facebook.com/permalink.php?story_fbid=1117725847490144&id=172307927585571');
    assert.equal(permalink.storyFbId, '1117725847490144');
    assert.equal(permalink.pageId, '172307927585571');

    // A token that is not a story id must not become a bogus filename.
    assert.equal(decodeStoryToken('not-base64-at-all'), null);
});

test('a cookies.txt becomes a Cookie header, HttpOnly cookies included', () => {
    const header = cookieHeaderFromNetscape(NETSCAPE);
    assert.equal(header, 'c_user=1234567890; xs=secret-session-value; fr=abc123');
    assert.ok(!header.includes('Netscape'), 'a comment must not be sent as a cookie');
    // Dropping the #HttpOnly_ marker line means losing `xs` and `c_user`, which
    // is every cookie that proves the session is real.
    assert.match(header, /xs=secret-session-value/);
    assert.match(header, /c_user=1234567890/);
    assert.equal(cookieHeaderFromNetscape('# only comments\n'), '');
});

test('no cookies fails with the one instruction the user can act on', async () => {
    await assert.rejects(
        () => fetchFacebookStory('https://www.facebook.com/stories/172307927585571/UzpfSVNDOjExMTc3MjU4NDc0OTAxNDQ=/', ''),
        (e) => {
            assert.ok(e instanceof FacebookStoryError);
            assert.equal(e.kind, 'no_cookies');
            assert.match(e.message, /Settings/);
            return true;
        }
    );
});

test('the header Facebook requires is actually sent', () => {
    // The regression this whole module was written for. Asserted on the source
    // because a missing header cannot be observed without a live story, and the
    // live check is skipped when no session is available.
    const source = fs.readFileSync(path.join(SRC, 'utils', 'facebookStories.ts'), 'utf8');
    assert.match(source, /'Sec-Fetch-Site': 'same-origin'/);
});

test('the handler resolves stories through this module, not inline scraping', () => {
    const handler = fs.readFileSync(path.join(SRC, 'handlers', 'infoHandler.ts'), 'utf8');
    assert.match(handler, /if \(isFacebook && isFacebookStoryUrl\(url\)\)/);
    assert.match(handler, /await fetchFacebookStory\(url, cookieHeader\)/);
    // The old inline version is the thing that 400'd; its regexes should not
    // reappear in the handler.
    assert.ok(!handler.includes('browser_native_hd_url'), 'parsing belongs in the module');
    assert.ok(!handler.includes('extractFbUrl'), 'parsing belongs in the module');
});

test('one story reads as one video, not as a tray holding one item', () => {
    // These three fields are the contract with the result card, and each one
    // breaks the UI quietly rather than loudly:
    //   singleStory   - without it the tray renders Select All / Download All
    //                   buttons that do nothing
    //   webpage_url   - the card's Download button resolves its target from
    //                   here, so the wrong value means no working download
    //   formats: []   - the card reads the empty list as "offer one download"
    const md = buildFacebookStoryMetadata({
        mediaUrl: 'https://scontent.fbcdn.net/v/t42.1234/n-media.mp4?oh=1&oe=2',
        thumbnailUrl: 'https://scontent.fbcdn.net/v/thumb.jpg',
        uploaderName: '  Some\n Page  ',
        ref: { pageId: '172307927585571', storyFbId: '1117725847490144' }
    });

    assert.equal(md.singleStory, true);
    assert.equal(md.webpage_url, 'https://scontent.fbcdn.net/v/t42.1234/n-media.mp4?oh=1&oe=2');
    assert.deepEqual(md.formats, []);
    assert.equal(md.contentType, 'story');
    assert.equal(md.entries.length, 1);
    assert.equal(md.entries[0].url, md.webpage_url, 'the tray entry and the card must point at the same media');
    // A name with a newline in it would become a two-line filename.
    assert.equal(md.uploader, 'Some Page');
    assert.equal(md.title, 'Story by Some Page');

    // No name from the page is still a usable label, not "Story by undefined".
    const anon = buildFacebookStoryMetadata({ mediaUrl: 'https://scontent.fbcdn.net/v/x.mp4', ref: {} });
    assert.equal(anon.uploader, 'Facebook');
    assert.equal(anon.title, 'Story by Facebook');
});

// --- live -------------------------------------------------------------------

const COOKIE_FILE = path.join(
    process.env.APPDATA || '',
    'vibe-downloader', 'cookies', 'cookies_facebook.txt'
);
const STORY_URL = 'https://www.facebook.com/stories/172307927585571/UzpfSVNDOjExMTc3MjU4NDc0OTAxNDQ=/?bucket_count=9';
const hasSession = fs.existsSync(COOKIE_FILE);

test('live: a real story resolves to a downloadable video', { skip: hasSession ? false : 'no saved Facebook session' }, async () => {
    const cookieHeader = cookieHeaderFromNetscape(fs.readFileSync(COOKIE_FILE, 'utf8'));
    const story = await fetchFacebookStory(STORY_URL, cookieHeader);

    assert.match(story.mediaUrl, /^https:\/\/[^ ]*fbcdn\.net\//, 'must be a direct CDN URL, not a page URL');

    // The part that matters: the URL the download button will be given has to
    // actually serve video bytes. "We found a URL" is not the same as "the user
    // gets a file".
    const res = await fetch(story.mediaUrl, { headers: { 'User-Agent': 'Mozilla/5.0' } });
    assert.ok(res.ok, `story media returned HTTP ${res.status}`);
    assert.match(res.headers.get('content-type') || '', /video\//);
    const bytes = Buffer.from(await res.arrayBuffer());
    assert.ok(bytes.length > 10_000, `story video was only ${bytes.length} bytes`);
    // 'ftyp' at offset 4 is what makes a download an mp4 rather than an error page.
    assert.equal(bytes.subarray(4, 8).toString('ascii'), 'ftyp', 'the downloaded bytes are not an mp4');
});

test('live: a stale session is reported as a login wall, not a parse failure', { skip: hasSession ? false : 'no saved Facebook session' }, async () => {
    await assert.rejects(
        () => fetchFacebookStory('https://www.facebook.com/stories/172307927585571/UzpfSVNDOjExMTc3MjU4NDc0OTAxNDQ=/', 'c_user=0; xs=invalid-session'),
        (e) => {
            assert.ok(e instanceof FacebookStoryError);
            assert.ok(['login_required', 'http_error'].includes(e.kind), `unexpected kind ${e.kind}`);
            return true;
        }
    );
});

test('live: the request shape still works, so the header has not been lost again', { skip: hasSession ? false : 'no saved Facebook session' }, async () => {
    // A 400 here means Facebook changed what it wants; the module comment says
    // not to delete Sec-Fetch-Site, and this is what notices when someone does.
    const cookieHeader = cookieHeaderFromNetscape(fs.readFileSync(COOKIE_FILE, 'utf8'));
    await fetchFacebookStory(STORY_URL, cookieHeader);
});
